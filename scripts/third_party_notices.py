#!/usr/bin/env python3
"""Generate full dependency license notices; verify built-binary and go.sum coverage."""
import argparse,hashlib,json,os,pathlib,subprocess,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
TARGETS=[('linux','amd64'),('linux','arm64'),('darwin','amd64'),('darwin','arm64'),('windows','amd64')]
NOTICE=ROOT/'THIRD_PARTY_NOTICES.md'
MANIFEST=ROOT/'scripts/third_party_manifest.json'

def command(go,args,extra=None):
 return subprocess.check_output([go,*args],cwd=ROOT,env=dict(os.environ,**(extra or {})),text=True)
def stream(text):
 decoder=json.JSONDecoder()
 while text.strip():
  text=text.lstrip();value,end=decoder.raw_decode(text);yield value;text=text[end:]
def production_modules(go):
 modules={}
 for system,arch in TARGETS:
  packages=stream(command(go,['list','-mod=readonly','-deps','-json','./cmd/lmmcp'],{'CGO_ENABLED':'0','GOOS':system,'GOARCH':arch}))
  for package in packages:
   module=package.get('Module')
   if module and not module.get('Main'):
    if module.get('Replace'):raise ValueError('license generator requires pinned modules without replacements')
    modules[module['Path']]=module
 return modules

def documents(directory):
 names=['LICENSE','LICENSE.txt','LICENSE.md','COPYING','COPYING.txt','NOTICE','NOTICE.txt','PATENTS']
 files=[(n,(directory/n).read_bytes().decode("utf-8")) for n in names if (directory/n).is_file()]
 if not any(n.startswith(('LICENSE','COPYING')) for n,_ in files):raise ValueError('dependency has no recognized license document')
 return files

def render(go):
 modules=production_modules(go)
 sums={(fields[0],fields[1]):fields[2] for line in (ROOT/'go.sum').read_text().splitlines() if len(fields:=line.split())==3}
 output=['# Third-party notices','','Generated by `python3 scripts/third_party_notices.py`. Full upstream license, patent and notice texts follow.','Coverage is the production dependency union across Linux amd64/arm64, macOS amd64/arm64 and Windows amd64, resolved from go.mod.','The Go runtime is included; separately installed development tools and test-only modules are not shipped in the binary.','']
 manifest={'format':1,'targets':[system+'/'+arch for system,arch in TARGETS],'modules':[]}
 entries=[('Go standard library and runtime','',pathlib.Path(command(go,['env','GOROOT']).strip()))]
 entries.extend((name,m['Version'],pathlib.Path(m['Dir'])) for name,m in sorted(modules.items()))
 for name,version,directory in entries:
  if version and (name,version) not in sums:raise ValueError('production module lacks its code checksum in go.sum: '+name)
  docs=documents(directory);record={'path':name,'version':version,'documents':[]}
  output+=['## '+name+('@'+version if version else ''),'']
  for filename,text in docs:
   record['documents'].append({'file':filename,'sha256':hashlib.sha256(text.encode()).hexdigest()})
   output+=['### '+filename,'','```text',text.rstrip('\n'),'```','']
  manifest['modules'].append(record)
 return '\n'.join(output)+'\n',json.dumps(manifest,indent=2)+'\n',modules,sums

def check_binaries(go,binaries,modules,sums):
 covered=set()
 for binary in binaries:
  for line in command(go,['version','-m',str(binary)]).splitlines():
   fields=line.split()
   if fields and fields[0]=='dep':
    path,version=fields[1:3]
    if path not in modules or modules[path]['Version']!=version or len(fields)!=4 or sums.get((path,version))!=fields[3]:raise ValueError('binary dependency lacks a matching notice/checksum: '+path+'@'+version)
    covered.add(path)
 if binaries and covered!=set(modules):raise ValueError('binary union does not cover the generated production module set')

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--go',default='go');parser.add_argument('--verify',action='store_true');parser.add_argument('--binary',action='append',type=pathlib.Path,default=[]);args=parser.parse_args()
 try:
  notice,manifest,modules,sums=render(args.go)
  if args.verify:
   if NOTICE.read_text()!=notice or MANIFEST.read_text()!=manifest:raise ValueError('third-party notices/manifest are stale; regenerate them')
  else:NOTICE.write_text(notice);MANIFEST.write_text(manifest)
  check_binaries(args.go,args.binary,modules,sums)
  print(json.dumps({'modules':len(modules),'runtime':True,'binaries':len(args.binary),'verified':args.verify}))
 except (OSError,ValueError,subprocess.CalledProcessError) as error:
  print('third-party notice verification failed: '+str(error),file=sys.stderr);return 1
 return 0
if __name__=='__main__':raise SystemExit(main())
